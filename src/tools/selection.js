// Робота з виділеним текстом: «переклади виділене», «виправ помилки», «скороти», «зроби ввічливіше».
// Код бере текст, виділений у вікні, де зараз курсор, окремим запитом до моделі (без інструментів) виконує
// над ним завдання й кладе результат у буфер обміну — або, якщо просили замінити, друкує на місце виділеного.
//
// Виділений текст — сторонні дані (це може бути шматок сайту з вказівками для моделі). У розмову він НЕ
// повертається: основна модель дізнається лише, що завдання виконано й скільки знаків вийшло. Тому розмова
// від цього не «забруднюється», а прочитане у виділеному не може нічого викликати.
import { str } from './util.js';

export const MAX_SELECTION = 5000;

export default [
  {
    // Запитання про виділений текст: «що тут написано», «про що це», «поясни». На відміну від edit_selection,
    // відповідь повертається в розмову (щоб асистент сказав її вголос), тому це сторонні дані з найвищим рівнем
    // недовіри — як вміст файлу чи екран: після цього запис нотаток, пошук і сайти потребують дозволу.
    name: 'ask_selection',
    confirm: 'tainted',
    untrusted: 'content',
    schema: () => ({
      description: 'Відповідає на запитання про текст, який користувач виділив у будь-якій програмі: що там написано, про що він, '
        + 'що означає, переказати, пояснити. Нічого не змінює й не копіює.',
      parameters: {
        type: 'object',
        properties: { question: { type: 'string', description: 'Що користувач хоче знати про виділений текст, його словами' } },
        required: ['question'],
      },
    }),
    describe: () => 'Прочитати виділений текст і відповісти на запитання про нього',
    async run({ question }, { os }) {
      if (typeof os.editSelection !== 'function') return { ok: false, error: 'Працювати з виділеним текстом зараз не можу' };
      return os.editSelection(str(question, 300) || 'Про що цей текст?', false, 'ask');
    },
  },
  {
    name: 'edit_selection',
    confirm: 'tainted',
    schema: () => ({
      description: 'Виконує завдання над текстом, який користувач виділив у будь-якій програмі: перекласти, виправити помилки, скоротити, '
        + 'переписати іншим тоном, пояснити. Результат кладе в буфер обміну; з replace=true друкує замість виділеного.',
      parameters: {
        type: 'object',
        properties: {
          task: { type: 'string', description: 'Що зробити з текстом, словами користувача: «переклади англійською», «виправ помилки»' },
          replace: { type: 'boolean', description: 'true — лише якщо користувач прямо просив замінити чи вставити результат на місце виділеного' },
        },
        required: ['task'],
      },
    }),
    describe: ({ task }, { taint }) => `Обробити виділений текст: «${str(task, 300)}».${taint > 0 ? ' Результат лише покажу в панелі: не друкуватиму його й не кластиму в буфер обміну, бо в цій розмові я читав сторонній текст.' : ''}`,
    async run({ task, replace }, { os, taint }) {
      if (typeof os.editSelection !== 'function') return { ok: false, error: 'Працювати з виділеним текстом зараз не можу' };
      const what = str(task, 300);
      if (!what) return { ok: false, error: 'Не сказано, що зробити з текстом' };
      // після читання стороннього текста «завдання» могла скласти вбудована інструкція: тоді результат нікуди не
      // друкується й буфер обміну не чіпається — його лише видно в панелі
      return os.editSelection(what, replace === true && !(taint > 0), 'edit', { showOnly: taint > 0 });
    },
  },
];
