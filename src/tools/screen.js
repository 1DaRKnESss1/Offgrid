// «Подивись на екран»: асистент робить знімок екрана й відповідає на питання про те, що на ньому видно.
//
// Екран — такий самий сторонній текст, як і вміст файлу: на ньому може бути відкритий сайт чи лист із
// вказівками, написаними для моделі. Тому:
//   * знімок розглядає ОКРЕМИЙ запит до моделі, в якого немає жодних інструментів, — прочитане там не може
//     нічого викликати;
//   * у розмову повертається лише текстовий опис, позначений як недовірені дані (рівень «вміст»): після цього
//     запис нотаток, пошук і сайти потребують дозволу кнопкою;
//   * якщо розмова вже «забруднена», сам погляд на екран теж потребує дозволу;
//   * знімок не зберігається: тимчасовий файл видаляється одразу, у журнал іде лише питання, а не побачене.
// Усе відбувається на цьому комп'ютері: і знімок, і модель локальні.
import { str } from './util.js';

export default [
  {
    name: 'look_at_screen',
    confirm: 'tainted',
    untrusted: 'content',
    schema: () => ({
      description: 'Дивиться на екран користувача (робить знімок) і каже, що на ньому видно: вікна, текст, помилки, зображення. '
        + 'Викликай, коли користувач питає про те, що зараз на екрані: «що тут написано», «що це за помилка», «що я зараз бачу».',
      parameters: {
        type: 'object',
        properties: { question: { type: 'string', description: 'Що саме треба дізнатися з екрана, словами користувача' } },
        required: ['question'],
      },
    }),
    describe: () => 'Зробити знімок екрана й показати його моделі (знімок нікуди не зберігається і не залишає комп\'ютер)',
    async run({ question }, { os }) {
      if (typeof os.see !== 'function') return { ok: false, error: 'Дивитися на екран зараз не можу.' };
      const seen = await os.see(str(question, 300) || 'Що зараз на екрані?');
      if (!seen.ok) return { ok: false, error: seen.error ?? 'Не вдалося подивитися на екран' };
      return { ok: true, message: 'Подивився на екран', on_screen: seen.text };
    },
  },
];
