// Модель любить закінчувати відповідь черговим «Чим ще можу допомогти?». У живій розмові це дратує,
// а промпт відучує її не до кінця — тож такий хвіст прибираємо кодом.
//
// «Черговим» вважаємо лише запитання про допомогу загалом: воно починається з «чим/що/як/чи», містить «ще»,
// а одразу після «ще» йде слово на кшталт «можу», «допомогти», «потрібно», «треба знати», «цікавить».
// Запитання по суті («Чи шукати ще в Завантаженнях?», «Що ще записати до списку?», «Який файл відкрити?»)
// сюди не підпадають — їх прибирати не можна, бо на них користувач відповідатиме.
const END = '(?![\\p{L}\\p{N}])';
const START = '(?<![\\p{L}\\p{N}])';
const HELP = `(?:(?:я|тобі|тебе|вам|вас)\\s+)?(?:можу|могла\\s+б|допомог\\p{L}*|потрібн\\p{L}*|треба(?:\\s+знати)?|цікавить|хочеш(?:\\s+(?:знати|дізнатис[ья]))?|бажаєш)${END}`;
const FILLER = new RegExp(
  `^(?:а\\s+)?(?:чим|що|як|чи)${END}[^.!?]{0,25}?${START}(?:ще|іще)\\s+${HELP}[^.!?]{0,30}\\?$`
  + `|^(?:потрібна|треба)\\s+(?:ще\\s+)?(?:якась\\s+)?допомога${END}[^.!?]{0,15}\\?$`, 'iu');

/** Чи є речення порожнім «черговим» запитанням наприкінці відповіді. */
export function isFiller(sentence) {
  return FILLER.test(String(sentence ?? '').trim());
}

/** Прибирає таке запитання з кінця відповіді, якщо перед ним є щось змістовне. */
export function stripFiller(text) {
  const full = String(text ?? '').trim();
  const m = full.match(/^([\s\S]*[.!?…]["»”)]*)\s+([^.!?…]+\?)$/);
  if (!m || !isFiller(m[2])) return full;
  return m[1].trim() || full;
}

/**
 * Що ще треба озвучити наприкінці відповіді.
 *   held  — речення, які притримали й ще не озвучили (запитання наприкінці);
 *   raw   — увесь текст, що надійшов від моделі потоком;
 *   reply — остаточна відповідь (вона ж на екрані й в історії).
 * Якщо з остаточної відповіді прибрано хвіст, з озвучення він теж прибирається — щоб почуте збігалося з побаченим.
 */
export function finalTail(held, raw, reply) {
  const tail = held.join(' ').trim();
  const full = String(raw ?? '').trim();
  const shown = String(reply ?? '').trim();
  if (!shown || !full.startsWith(shown)) return tail;
  const removed = full.slice(shown.length).trim();
  if (removed && tail.endsWith(removed)) return tail.slice(0, tail.length - removed.length).trim();
  return tail;
}
