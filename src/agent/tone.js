// ---------- Манера співрозмовника ----------
// Мала модель сама погано відчуває, ЯК із нею говорять, зате добре виконує коротку пряму вказівку. Тому манеру
// репліки визначає код (за словами й довжиною), а модель отримує підказку поруч із питанням. Підказка йде лише
// в запит, не в історію.
const W = (words) => new RegExp(`(?<![\\p{L}\\p{N}])(?:${words})(?![\\p{L}\\p{N}])`, 'iu');
const CASUAL = W('бро|братан|чел|чувак|йо|хай|здоров|шо|чо|шось|ща|щас|тіпа|типу|короче|крч|блін|капець|жесть|норм|нормас|ок|окей|пон|лол|кек|хах\\p{L}*|ахах\\p{L}*|ваще|взагалі-то|кароч|чікі|пукі|топ|кайф|круто|фігня|прикол\\p{L}*');
const POLITE = W('будь ласка|будьте ласкаві|чи не міг би ти|чи не могли б ви|прошу|дякую заздалегідь|поясніть|скажіть|підкажіть|вибачте|перепрошую');
const UPSET = W('не працює|знову|знов|скільки можна|дістало|бісить|набридло|та що таке|чому не|не так|я ж казав|я ж просив|ще раз кажу|дурн\\p{L}*|туп\\p{L}*');
const DETAIL = W('поясни|пояснити|розкажи|розповіси|чому|навіщо|як працює|як це працює|у чому різниця|чим відрізняється|докладно|детально|порівняй|що таке');

/** Коротка вказівка моделі, як відповісти на цю репліку, або '' — якщо нічого особливого. */
export function styleHint(text) {
  const t = String(text ?? '').trim();
  if (!t) return '';
  const words = t.split(/\s+/).length;
  const hints = [];
  if (UPSET.test(t) || /[!?]{2,}/.test(t)) hints.push('співрозмовник роздратований або щось не вийшло — відповідай спокійно, без виправдань і без бадьорості, одразу до справи');
  else if (CASUAL.test(t)) hints.push('співрозмовник говорить розкуто — відповідай так само просто й легко, розмовними словами, без офіціозу');
  else if (POLITE.test(t)) hints.push('співрозмовник говорить ввічливо й діловито — тримай такий самий рівний тон');
  if (DETAIL.test(t) || words >= 25) hints.push('він хоче пояснення — дай три-чотири змістовні речення');
  else if (words <= 4) hints.push('репліка коротка — відповідай одним коротким реченням');
  return hints.length ? `\n(Манера відповіді: ${hints.join('; ')}.)` : '';
}

// ---------- Диктування ----------
// «Офгрід, диктування» вмикає режим, у якому сказане друкується у вікно, де стоїть курсор (модель у цьому
// участі не бере). «Кінець диктування» чи «стоп диктування» — вимикає.
const DICTATE_ON = /^(?:(?:увімкни|почни|запусти|ввімкни)\s+)?(?:режим\s+)?(?:диктуванн[яю]|диктовк[ауи]|диктую|друкуй\s+(?:за\s+мною|під\s+диктовку)|пиши\s+під\s+диктовку)[.!\s]*$/iu;
const DICTATE_OFF = /^(?:кінець|стоп|зупини|закінчи|вимкни|досить)\s+(?:диктуванн[яю]|диктовк[ауи]|диктувати)[.!\s]*$|^(?:кінець|стоп)[.!\s]*$/iu;
export const startsDictation = (text) => DICTATE_ON.test(String(text ?? '').trim());
export const endsDictation = (text) => DICTATE_OFF.test(String(text ?? '').trim());

// «переклади виділене», «виправ помилки у виділеному тексті» — модель схильна просити сам текст, хоча має
// інструмент, який його бере. Агент один раз нагадає про інструмент (як і з екраном).
const ABOUT_SELECTION = /виділен|виділив|виділила|вибран(?:ий|ого|ому|им)\s+текст/iu;
export const asksAboutSelection = (text) => ABOUT_SELECTION.test(String(text ?? ''));

// ---------- Прохання, для яких інструмент потрібен напевно ----------
const ASKS_TIME = /котра\s+(?:зараз\s+)?година|котрий\s+(?:зараз\s+)?час|скільки\s+(?:зараз\s+)?(?:часу|годин)|як(?:е|ий)\s+(?:сьогодні|зараз)\s+(?:число|день)|яка\s+(?:сьогодні\s+|зараз\s+)?дата/iu;
const SCREEN_NUDGE = 'Ти не бачиш екран, доки не викличеш інструмент look_at_screen. Виклич його зараз і розкажи, що він показав.';
const SELECTION_NUDGE = 'Виділений текст бере інструмент edit_selection — тобі його бачити не треба. Виклич edit_selection просто зараз, передавши в task, що зробити з текстом.';

// «запам'ятай, що…» і «що ти пам'ятаєш про…» — теж однозначні: модель інколи відповідає «запам'ятав», нічого не зберігши
// Музика й відео: команди без варіантів, тож їх теж виконує код одразу. (На них модель інколи відповідала
// луною — повторювала сказане — і нічого не робила.)
const PLAYS = '(?:музик\\p{L}*|пісн\\p{L}*|песн\\p{L}*|трек\\p{L}*|відео|видео|відтворення|ютуб\\p{L}*|youtube|spotify|спотіфа\\p{L}*|плеєр\\p{L}*|фільм\\p{L}*|серіал\\p{L}*|звук\\p{L}*)';
const MEDIA_PAUSE = new RegExp(`на\\s+пауз[уі]|^пауза[.!\\s]*$|(?:зупини|вимкни|виключи|стопни|припини)\\s+(?:\\p{L}+\\s+){0,2}${PLAYS}|^стоп\\s+${PLAYS}`, 'iu');
const MEDIA_PLAY = new RegExp(`зніми\\s+(?:\\p{L}+\\s+){0,2}з\\s+паузи|(?:продовж\\p{L}*|віднови|відновлюй|запусти|увімкни|ввімкни|включи|грай)\\s+(?:\\p{L}+\\s+){0,2}${PLAYS}|^(?:грай|грай\\s+далі|продовжуй|продовж|плей)[.!\\s]*$|щоб\\s+(?:\\p{L}+\\s+){0,2}грал[аои]`, 'iu');
const MEDIA_NEXT = new RegExp(`наступн\\p{L}*\\s+${PLAYS}|${PLAYS}\\s+далі|(?:перемкни|переключи|скіпни|пропусти)\\s+(?:\\p{L}+\\s+){0,2}${PLAYS}|^(?:наступн\\p{L}*|далі)[.!\\s]*$`, 'iu');
const MEDIA_PREV = new RegExp(`попередн\\p{L}*\\s+${PLAYS}|(?:поверни|верни)\\s+(?:\\p{L}+\\s+){0,2}попередн|^(?:попередн\\p{L}*|назад)[.!\\s]*$`, 'iu');
const VOLUME_UP = /гучніше|голосніше|додай\s+(?:гучност|звук)|збільш\p{L}*\s+(?:гучніст|звук)/iu;
const VOLUME_DOWN = /тихіше|зменш\p{L}*\s+(?:гучніст|звук)|прибери\s+(?:гучніст|звук)/iu;
const VOLUME_MUTE = /^(?:вимкни|виключи|увімкни|ввімкни|поверни)\s+звук[.!\s]*$|без\s+звуку/iu;
const RUN_SCENARIO = /^(?:будь\s+ласка[,\s]+)?(?:запусти|запускай|увімкни|ввімкни|вмикай|включи|активуй|виконай)\s+(?:сценарій\s+)?(.{2,40}?)[.!\s]*$/iu;
const REMEMBER = /^(?:будь\s+ласка[,\s]+)?запам['’ʼ]?ятай(?:[,:\s]+(?:що|будь\s+ласка))?[,:\s]+(.+)$/isu;
const RECALL = /що\s+ти\s+(?:про\s+мене\s+)?пам['’ʼ]?ятаєш|що\s+я\s+(?:тобі\s+)?(?:казав|говорив|просив\s+запам)|ти\s+пам['’ʼ]?ятаєш/iu;

/**
 * Якщо прохання однозначно потребує інструмента — який саме і з якими аргументами.
 * nudge — чим спершу нагадати моделі; без нього інструмент викликається одразу, якщо модель його не викликала.
 * direct — викликати ще до звернення до моделі (команда без варіантів).
 */
export function requiredTool(input, toolNames = [], { findScenario = null } = {}) {
  const has = (name) => toolNames.includes(name);
  const text = String(input ?? '').trim().slice(0, 300);
  if (has('edit_selection') && asksAboutSelection(text)) return { tool: 'edit_selection', args: { task: text }, nudge: SELECTION_NUDGE };
  if (has('look_at_screen') && asksAboutScreen(text)) return { tool: 'look_at_screen', args: { question: text }, nudge: SCREEN_NUDGE };
  if (has('get_time') && ASKS_TIME.test(text) && text.length <= 60) return { tool: 'get_time', args: {} };
  // «запусти режим гри»: якщо такий сценарій справді збережено — запускаємо його, а не чекаємо, що модель здогадається
  const launch = has('scenario') && findScenario ? RUN_SCENARIO.exec(text) : null;
  if (launch) { const found = findScenario(launch[1]); if (found) return { tool: 'scenario', args: { action: 'run', name: found.name }, direct: true }; }
  if (has('change_volume') && text.length <= 60) {
    const vol = VOLUME_UP.test(text) ? 'up' : VOLUME_DOWN.test(text) ? 'down' : VOLUME_MUTE.test(text) ? 'mute' : null;
    if (vol) return { tool: 'change_volume', args: { action: vol, amount: /трохи|трішки|ледь|трошки/iu.test(text) ? 'small' : /набагато|значно|сильно|дуже/iu.test(text) ? 'large' : 'medium' }, direct: true };
  }
  if (has('control_pc') && text.length <= 90) {
    const media = MEDIA_PAUSE.test(text) ? 'pause' : MEDIA_PLAY.test(text) ? 'play' : MEDIA_NEXT.test(text) ? 'next_track' : MEDIA_PREV.test(text) ? 'previous_track' : null;
    if (media) return { tool: 'control_pc', args: { action: media }, direct: true };
  }
  const fact = REMEMBER.exec(text);
  if (has('memory') && fact && fact[1].trim().length >= 3) return { tool: 'memory', args: { action: 'remember', text: fact[1].trim() } };
  if (has('memory') && RECALL.test(text)) return { tool: 'memory', args: { action: 'recall', text } };
  return null;
}

// ---------- Пам'ять у розмові ----------
// Те, що користувач просив запам'ятати і що стосується нинішньої репліки, код сам додає до запиту — модель
// не мусить здогадатися «згадати». Іде лише в запит, не в історію.
export function memoryHint(store, text) {
  if (!store || typeof store.recall !== 'function') return '';
  let facts = [];
  try { facts = stemsWorthRecalling(text) ? store.recall(text, 3) : []; } catch { return ''; }
  if (facts.length === 0) return '';
  return `\n(Користувач раніше просив тебе запам'ятати: ${facts.map((f) => `«${f.text}»`).join('; ')}. Якщо це стосується його репліки — відповідай за цим, не кажи «не знаю».)`;
}
// на привітання, подяку й зовсім короткі репліки пам'ять не підтягуємо
const stemsWorthRecalling = (text) => String(text ?? '').trim().split(/\s+/).length >= 2;

// ---------- Луна ----------
// Модель іноді повторює слова користувача («постав на паузу» -> «Постав на паузу.») або свою попередню репліку.
// Це не відповідь: агент один раз просить її відповісти по суті.
const bare = (t) => String(t ?? '').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, '');
export function isEcho(reply, input, previousReply = '') {
  const r = bare(reply);
  if (r.length < 4 || r.length > 120) return false;
  const i = bare(input);
  // «Добре, зроби гучніше.» — ті самі слова з коротким додатком теж луна
  if (r === i || (i.length >= 8 && r.includes(i) && r.length <= i.length + 12)) return true;
  return !!previousReply && r === bare(previousReply) && i !== r;
}
