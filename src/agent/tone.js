// Модель любить закінчувати відповідь черговим «Чим ще можу допомогти?». У живій розмові це дратує,
// а промпт відучує її не до кінця — тож такий хвіст прибираємо кодом.
//
// «Черговим» вважаємо лише запитання про допомогу загалом: воно починається з «чим/що/як/чи», містить «ще»,
// а одразу після «ще» йде слово на кшталт «можу», «допомогти», «потрібно», «треба знати», «цікавить».
// Запитання по суті («Чи шукати ще в Завантаженнях?», «Що ще записати до списку?», «Який файл відкрити?»)
// сюди не підпадають — їх прибирати не можна, бо на них користувач відповідатиме.
const END = '(?![\\p{L}\\p{N}])';
const START = '(?<![\\p{L}\\p{N}])';
const HELP = `(?:(?:я|тобі|тебе|вам|вас)\\s+)?(?:можу|могла\\s+б|допомог\\p{L}*|потрібн\\p{L}*|треба(?:\\s+знати)?|цікавить|хочеш(?:\\s+(?:знати|дізнатис[ья]))?|бажаєш)${END}`;
const FILLER = new RegExp(
  `^(?:а\\s+)?(?:чим|що|як|чи)${END}[^.!?]{0,25}?${START}(?:ще|іще)\\s+${HELP}[^.!?]{0,30}\\?$`
  + `|^(?:потрібна|треба)\\s+(?:ще\\s+)?(?:якась\\s+)?допомога${END}[^.!?]{0,15}\\?$`, 'iu');

/** Чи є речення порожнім «черговим» запитанням наприкінці відповіді. */
export function isFiller(sentence) {
  return FILLER.test(String(sentence ?? '').trim());
}

/** Прибирає таке запитання з кінця відповіді, якщо перед ним є щось змістовне. */
export function stripFiller(text) {
  const full = String(text ?? '').trim();
  const m = full.match(/^([\s\S]*[.!?…]["»”)]*)\s+([^.!?…]+\?)$/);
  if (!m || !isFiller(m[2])) return full;
  return m[1].trim() || full;
}

/**
 * Що ще треба озвучити наприкінці відповіді.
 *   held  — речення, які притримали й ще не озвучили (запитання наприкінці);
 *   raw   — увесь текст, що надійшов від моделі потоком;
 *   reply — остаточна відповідь (вона ж на екрані й в історії).
 * Якщо з остаточної відповіді прибрано хвіст, з озвучення він теж прибирається — щоб почуте збігалося з побаченим.
 */
export function finalTail(held, raw, reply) {
  const tail = held.join(' ').trim();
  const full = String(raw ?? '').trim();
  const shown = String(reply ?? '').trim();
  if (!shown || !full.startsWith(shown)) return tail;
  const removed = full.slice(shown.length).trim();
  if (removed && tail.endsWith(removed)) return tail.slice(0, tail.length - removed.length).trim();
  return tail;
}

// ---------- «Сказав, але не зробив» ----------
// Модель інколи замість виклику інструмента описує намір: «Зараз перевірю час», «Використаю інструмент
// write_note». Таку репліку агент не приймає як відповідь, а один раз просить модель діяти.
const NOT_LETTER = '(?![\\p{L}\\p{N}])';
// обіцянка в майбутньому часі — намір, навіть якщо якийсь інструмент у цьому ході вже викликано
// («не зроблю» — це відмова, а не намір, тому заперечення перед дієсловом виключаємо)
const WILL_DO = new RegExp(`(?<!не\\s)${START}(?:використаю|скористаюс[ья]|викличу|запишу|перевірю|пошукаю|дізнаюс[ья]|запитаю|виконаю|запущу|відкрию|закрию|`
  + `знайду|зроблю|зменшу|збільшу|вимкну|увімкну|зміню|створю|прочитаю|гляну|подивлюс[ья]|перекладу|виправлю|скорочу|перепишу|згорну|`
  + `поверну|поставлю|нагадаю|заблокую|перемкну|додам|збережу|надрукую)${NOT_LETTER}`, 'iu');
// «роблю просто зараз» — намір лише тоді, коли в цьому ході ще нічого не зроблено (після інструмента це звичайний звіт)
const DOING = new RegExp(`${START}(?:шукаю|запитую|перевіряю|відкриваю|закриваю|записую|запускаю|виконую|дивлюс[ья]|викликаю|згортаю|`
  + `перекладаю|виправляю|ставлю|блокую|перемикаю|додаю|зберігаю|друкую|зменшую|збільшую|вимикаю|вмикаю|`
  + `(?:потрібно|треба|слід)\\s+(?:дізнатис[ья]|перевірити|використати|викликати|знайти|запитати))${NOT_LETTER}`, 'iu');
// «зробив», «зроблено», коли в цьому ході не викликано жодного інструмента, — неправда: дії не було
const CLAIMS_DONE = new RegExp(`^(?:(?:готово|гаразд|добре|окей)[.,!\\s]+)?(?:(?:зроблено|виконано|готово)${NOT_LETTER}|(?:я\\s+)?(?:зробив|відкрив|закрив|`
  + `записав|поставив|згорнув|повернув|додав|вимкнув|увімкнув|переклав|виправив|скоротив|заблокував|зберіг|надрукував|перемкнув|зменшив|`
  + `збільшив|запустив)${NOT_LETTER})`, 'iu');

// слова, з якими «зроблю» означає не «роблю зараз», а «можу», «потім» або «не буду»
const NOT_NOW = new RegExp(`${START}(?:якщо|коли|щойно|скажи|скажеш|хочеш|дозволь|дозволиш|можу|можемо|вмію|здатен|пізніше|потім|згодом|
спершу|спочатку|не\\s+(?:можу|буду|вмію|маю|стану))${NOT_LETTER}`.replace(/\n/g, ''), 'iu');

/**
 * Чи це опис наміру замість дії.
 *   toolNames — назви інструментів (якщо модель називає інструмент у відповіді — вона точно не відповідь дає);
 *   didSomething — у цьому ході вже викликано хоч один інструмент.
 */
export function announcesIntent(text, toolNames = [], didSomething = false) {
  const t = String(text ?? '').trim();
  if (!t || t.length > 400) return false;
  // Запитання, умова, пропозиція, відмова чи розповідь про можливості — це не намір діяти зараз.
  // Тут краще недопрацювати, ніж зробити те, про що не просили: помилка в цей бік — це зайва дія.
  if (t.includes('?')) return false;
  // Модель назвала інструмент на ім'я («використаю open_website…») — користувачеві так не кажуть, це думка вголос.
  // Рахується, лише поки нічого не зроблено: після виклику вона може згадати інструмент у звіті.
  if (!didSomething && toolNames.some((name) => name && t.includes(name))) return true;
  if (NOT_NOW.test(t)) return false;
  if (WILL_DO.test(t)) return true;
  return !didSomething && (DOING.test(t) || CLAIMS_DONE.test(t));
}

// ---------- «На цьому все» ----------
// Фрази, якими людина закінчує розмову. Після такої асистент не відповідає по суті й не слухає далі.
const GOODBYE = new RegExp(`^(?:(?:ну\\s+)?(?:добре|гаразд|окей|ок|дякую|спасибі)[,.!\\s]+)*(?:`
  + `(?:я\\s+)?(?:повернус[ья]|звернус[ья]|покличу|напишу)\\s+(?:потім|по\\s*т[иі]м|пізніше|згодом)`
  + `|(?:на\\s+цьому|це|поки|наразі)\\s+(?:все|усе)`
  + `|(?:все|усе|досить|вистачить)(?:\\s*,?\\s*(?:дякую|спасибі))?`
  + `|(?:дякую|спасибі)[,\\s]+(?:це\\s+)?(?:все|усе|досить|більше\\s+нічого)`
  + `|більше\\s+нічого(?:\\s+не\\s+(?:треба|потрібно))?`
  + `|до\\s+побачення|бувай|па-?па|на\\s+все\\s+добре|відпочивай|можеш\\s+(?:йти|відпочивати|спати)`
  + `)[.!\\s]*$`, 'iu');

export function isGoodbye(text) {
  const t = String(text ?? '').trim();
  return t.length > 0 && t.length <= 60 && GOODBYE.test(t);
}

// ---------- «Що в мене на екрані?» ----------
// Модель часом відповідає на таке з голови («бачу вікно з…»), не подивившись. Якщо питання про екран, а
// інструмент не викликано — агент один раз нагадає, що без нього вона нічого не бачить.
const ABOUT_SCREEN = /(?:на|з|із)\s+(?:моєму\s+|моїм\s+|цьому\s+|цим\s+)?(?:екран|монітор|диспле)|що\s+(?:ти\s+)?(?:тут\s+|зараз\s+|у\s+мене\s+|в\s+мене\s+)*бачиш|подивис[ья]\s+на\s+екран|глянь\s+на\s+екран/iu;

export function asksAboutScreen(text) {
  return ABOUT_SCREEN.test(String(text ?? ''));
}

// ---------- Манера співрозмовника ----------
// Мала модель сама погано відчуває, ЯК із нею говорять, зате добре виконує коротку пряму вказівку. Тому манеру
// репліки визначає код (за словами й довжиною), а модель отримує підказку поруч із питанням. Підказка йде лише
// в запит, не в історію.
const W = (words) => new RegExp(`(?<![\\p{L}\\p{N}])(?:${words})(?![\\p{L}\\p{N}])`, 'iu');
const CASUAL = W('бро|братан|чел|чувак|йо|хай|здоров|шо|чо|шось|ща|щас|тіпа|типу|короче|крч|блін|капець|жесть|норм|нормас|ок|окей|пон|лол|кек|хах\\p{L}*|ахах\\p{L}*|ваще|взагалі-то|кароч|чікі|пукі|топ|кайф|круто|фігня|прикол\\p{L}*');
const POLITE = W('будь ласка|будьте ласкаві|чи не міг би ти|чи не могли б ви|прошу|дякую заздалегідь|поясніть|скажіть|підкажіть|вибачте|перепрошую');
const UPSET = W('не працює|знову|знов|скільки можна|дістало|бісить|набридло|та що таке|чому не|не так|я ж казав|я ж просив|ще раз кажу|дурн\\p{L}*|туп\\p{L}*');
const DETAIL = W('поясни|пояснити|розкажи|розповіси|чому|навіщо|як працює|як це працює|у чому різниця|чим відрізняється|докладно|детально|порівняй|що таке');

/** Коротка вказівка моделі, як відповісти на цю репліку, або '' — якщо нічого особливого. */
export function styleHint(text) {
  const t = String(text ?? '').trim();
  if (!t) return '';
  const words = t.split(/\s+/).length;
  const hints = [];
  if (UPSET.test(t) || /[!?]{2,}/.test(t)) hints.push('співрозмовник роздратований або щось не вийшло — відповідай спокійно, без виправдань і без бадьорості, одразу до справи');
  else if (CASUAL.test(t)) hints.push('співрозмовник говорить розкуто — відповідай так само просто й легко, розмовними словами, без офіціозу');
  else if (POLITE.test(t)) hints.push('співрозмовник говорить ввічливо й діловито — тримай такий самий рівний тон');
  if (DETAIL.test(t) || words >= 25) hints.push('він хоче пояснення — дай три-чотири змістовні речення');
  else if (words <= 4) hints.push('репліка коротка — відповідай одним коротким реченням');
  return hints.length ? `\n(Манера відповіді: ${hints.join('; ')}.)` : '';
}

// ---------- Диктування ----------
// «Офгрід, диктування» вмикає режим, у якому сказане друкується у вікно, де стоїть курсор (модель у цьому
// участі не бере). «Кінець диктування» чи «стоп диктування» — вимикає.
const DICTATE_ON = /^(?:(?:увімкни|почни|запусти|ввімкни)\s+)?(?:режим\s+)?(?:диктуванн[яю]|диктовк[ауи]|диктую|друкуй\s+(?:за\s+мною|під\s+диктовку)|пиши\s+під\s+диктовку)[.!\s]*$/iu;
const DICTATE_OFF = /^(?:кінець|стоп|зупини|закінчи|вимкни|досить)\s+(?:диктуванн[яю]|диктовк[ауи]|диктувати)[.!\s]*$|^(?:кінець|стоп)[.!\s]*$/iu;
export const startsDictation = (text) => DICTATE_ON.test(String(text ?? '').trim());
export const endsDictation = (text) => DICTATE_OFF.test(String(text ?? '').trim());

// «переклади виділене», «виправ помилки у виділеному тексті» — модель схильна просити сам текст, хоча має
// інструмент, який його бере. Агент один раз нагадає про інструмент (як і з екраном).
const ABOUT_SELECTION = /виділен|виділив|виділила|вибран(?:ий|ого|ому|им)\s+текст/iu;
export const asksAboutSelection = (text) => ABOUT_SELECTION.test(String(text ?? ''));

// ---------- Прохання, для яких інструмент потрібен напевно ----------
const ASKS_TIME = /котра\s+(?:зараз\s+)?година|котрий\s+(?:зараз\s+)?час|скільки\s+(?:зараз\s+)?(?:часу|годин)|як(?:е|ий)\s+(?:сьогодні|зараз)\s+(?:число|день)|яка\s+(?:сьогодні\s+|зараз\s+)?дата/iu;
const SCREEN_NUDGE = 'Ти не бачиш екран, доки не викличеш інструмент look_at_screen. Виклич його зараз і розкажи, що він показав.';
const SELECTION_NUDGE = 'Виділений текст бере інструмент edit_selection — тобі його бачити не треба. Виклич edit_selection просто зараз, передавши в task, що зробити з текстом.';

/**
 * Якщо прохання однозначно потребує інструмента — який саме і з якими аргументами.
 * nudge — чим спершу нагадати моделі; без нього інструмент викликається одразу.
 */
export function requiredTool(input, toolNames = []) {
  const has = (name) => toolNames.includes(name);
  const text = String(input ?? '').trim().slice(0, 300);
  if (has('edit_selection') && asksAboutSelection(text)) return { tool: 'edit_selection', args: { task: text }, nudge: SELECTION_NUDGE };
  if (has('look_at_screen') && asksAboutScreen(text)) return { tool: 'look_at_screen', args: { question: text }, nudge: SCREEN_NUDGE };
  if (has('get_time') && ASKS_TIME.test(text) && text.length <= 60) return { tool: 'get_time', args: {} };
  return null;
}
