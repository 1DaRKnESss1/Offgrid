// Модель любить закінчувати відповідь черговим «Чим ще можу допомогти?». У живій розмові це дратує,
// а промпт відучує її не до кінця — тож такий хвіст прибираємо кодом.
// Ознака «чергового» запитання: коротке, починається з «чим/що/як/чи» і містить слово «ще»
// («Чим ще можу допомогти?», «Що ще потрібно?»), або це «Потрібна ще допомога?».
// Змістовні запитання («Який файл відкрити?», «Що хочеш написати?») під неї не підпадають.
const WORD_END = '(?![\\p{L}\\p{N}])';
const FILLER = new RegExp(
  `^(?:а\\s+)?(?:чим|що|як|чи)${WORD_END}[^.!?]{0,40}?(?<![\\p{L}\\p{N}])(?:ще|іще)${WORD_END}[^.!?]{0,40}\\?$`
  + `|^(?:потрібна|треба)${WORD_END}[^.!?]{0,20}допомог[аи]${WORD_END}[^.!?]{0,20}\\?$`, 'iu');

/** Чи є речення порожнім «черговим» запитанням наприкінці відповіді. */
export function isFiller(sentence) {
  return FILLER.test(String(sentence ?? '').trim());
}

/** Прибирає таке запитання з кінця відповіді, якщо перед ним є щось змістовне. */
export function stripFiller(text) {
  const full = String(text ?? '').trim();
  const m = full.match(/^([\s\S]*[.!?…]["»”)]*)\s+([^.!?…]+\?)$/);
  if (!m || !isFiller(m[2])) return full;
  return m[1].trim() || full;
}
